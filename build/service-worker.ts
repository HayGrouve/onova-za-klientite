import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import type { Plugin } from 'vite'

/** The shell TanStack Start prerenders in SPA mode (ADR 0010). */
const SHELL = '/_shell.html'

function listPublicFiles(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return listPublicFiles(path, root)
    if (name === 'robots.txt' || name.startsWith('.')) return []
    return ['/' + relative(root, path).split('\\').join('/')]
  })
}

/**
 * Emits `/sw.js` with the client build's file list. A small hand-written
 * worker instead of vite-plugin-pwa, which doesn't support the Vite
 * Environment API that Start builds on.
 */
export function serviceWorker(): Plugin {
  return {
    name: 'onova:service-worker',
    apply: 'build',
    applyToEnvironment: (environment) => environment.name === 'client',
    generateBundle(_options, bundle) {
      const publicDir = this.environment.config.publicDir
      const files = [
        SHELL,
        ...Object.keys(bundle)
          .filter((file) => !file.endsWith('.map'))
          .map((file) => '/' + file),
        ...(publicDir ? listPublicFiles(publicDir) : []),
      ]
      const precache = [...new Set(files)].sort()
      const version = createHash('sha256')
        .update(precache.join('\n'))
        .digest('hex')
        .slice(0, 12)
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: workerSource(version, precache),
      })
    },
  }
}

function workerSource(version: string, precache: string[]) {
  return `// Generated by build/service-worker.ts. Do not edit.
const CACHE = 'shell-${version}'
const SHELL = ${JSON.stringify(SHELL)}
const PRECACHE = ${JSON.stringify(precache)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  )
})

// A new version waits until the app asks it to take over.
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  // Clerk, Convex and server functions always go to the network.
  if (url.origin !== self.location.origin) return
  if (url.pathname.startsWith('/_serverFn')) return

  if (request.mode === 'navigate') {
    event.respondWith(
      caches
        .match(SHELL)
        .then((cached) => cached || fetch(request)),
    )
    return
  }

  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request)),
  )
})
`
}
