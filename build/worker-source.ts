/**
 * The old address. A worker running there says goodbye instead of serving the
 * app (#53, plan decision 13): the host is matched exactly, so previews,
 * `klientite.onovaza.com` and `localhost` keep the normal worker.
 */
export const FAREWELL_HOST = 'onova-za-klientite.vercel.app'
export const NEW_ORIGIN = 'https://klientite.onovaza.com'
/** `idb-keyval`'s default database: the offline snapshot (`src/lib/offline-store.ts`). */
const SNAPSHOT_DB = 'keyval-store'

export type WorkerManifest = {
  version: string
  shell: string
  shellFiles: string[]
  assets: string[]
  precache: string[]
}

/**
 * The worker's source. Two caches:
 * - `shell-<version>`: the shell HTML, icons and manifest. Small, replaced on
 *   every deploy, fetched past the HTTP cache.
 * - `assets`: hashed `/assets/*` files, which never change under one name. It
 *   outlives deploys. An install adds only what is missing, and activation
 *   drops what this build no longer lists. Files outside the precache list
 *   (lazy chunks, extra font subsets) are added the first time they are asked
 *   for, then served from here.
 *
 * On the old host (`FAREWELL_HOST`) none of that runs. The worker takes over
 * at once, deletes every cache and the offline snapshot, sends each open
 * window to the same path and query on the new host, and unregisters itself.
 * It has no fetch handler there, so requests go to the network, where the old
 * host redirects (every path but `/sw.js`). Remove this branch a year after
 * the cutover (#55).
 */
export function workerSource(manifest: WorkerManifest) {
  return `// Generated by build/service-worker.ts. Do not edit.
const SHELL_CACHE = 'shell-${manifest.version}'
const ASSET_CACHE = 'assets'
const SHELL = ${JSON.stringify(manifest.shell)}
const SHELL_FILES = ${JSON.stringify([manifest.shell, ...manifest.shellFiles])}
const ASSETS = ${JSON.stringify(manifest.assets)}
const PRECACHE = ${JSON.stringify(manifest.precache)}

const pathOf = (request) => new URL(request.url).pathname

if (self.location.hostname === ${JSON.stringify(FAREWELL_HOST)}) {
  farewell()
} else {
  app()
}

function farewell() {
  self.addEventListener('install', () => {
    self.skipWaiting()
  })

  // An open page keeps its snapshot connection, so the delete reports
  // "blocked" and finishes once the page has navigated away: don't wait for it.
  const deleteSnapshot = () =>
    new Promise((resolve) => {
      const request = indexedDB.deleteDatabase(${JSON.stringify(SNAPSHOT_DB)})
      request.onsuccess = request.onerror = request.onblocked = () => resolve()
    })

  const sendToNewHost = () =>
    self.clients
      .claim()
      .then(() => self.clients.matchAll({ type: 'window', includeUncontrolled: true }))
      .then((windows) =>
        Promise.all(
          windows.map((client) => {
            const url = new URL(client.url)
            const target = ${JSON.stringify(NEW_ORIGIN)} + url.pathname + url.search
            return client.navigate(target).catch(() => null)
          }),
        ),
      )

  const deleteCaches = () =>
    caches.keys().then((keys) => Promise.all(keys.map((key) => caches.delete(key))))
  const unregister = () => self.registration.unregister()

  // In this order; a step that fails doesn't stop the next one.
  const steps = [deleteCaches, deleteSnapshot, sendToNewHost, unregister]
  self.addEventListener('activate', (event) => {
    event.waitUntil(
      steps.reduce((done, run) => done.then(run).catch(() => null), Promise.resolve()),
    )
  })
}

function app() {
  self.addEventListener('install', (event) => {
    event.waitUntil(
      Promise.all([
        caches
          .open(SHELL_CACHE)
          .then((cache) =>
            cache.addAll(SHELL_FILES.map((url) => new Request(url, { cache: 'reload' }))),
          ),
        caches.open(ASSET_CACHE).then(async (cache) => {
          const have = new Set((await cache.keys()).map(pathOf))
          return cache.addAll(PRECACHE.filter((url) => !have.has(url)))
        }),
      ]),
    )
  })

  self.addEventListener('activate', (event) => {
    const valid = new Set(ASSETS)
    event.waitUntil(
      Promise.all([
        caches
          .keys()
          .then((keys) =>
            Promise.all(
              keys
                .filter((key) => key !== SHELL_CACHE && key !== ASSET_CACHE)
                .map((key) => caches.delete(key)),
            ),
          ),
        caches.open(ASSET_CACHE).then(async (cache) => {
          const stale = (await cache.keys()).filter((request) => !valid.has(pathOf(request)))
          return Promise.all(stale.map((request) => cache.delete(request)))
        }),
      ]).then(() => self.clients.claim()),
    )
  })

  // A new version waits until the app asks it to take over.
  self.addEventListener('message', (event) => {
    if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting()
  })

  // Web Push (ADR 0011). Declarative Web Push is shown by the browser on iOS
  // 18.4+ without this code. Everywhere else the payload arrives here in the
  // same shape, and a notification is always shown (iOS drops the subscription
  // of a worker that receives a push and shows nothing).
  self.addEventListener('push', (event) => {
    let title = ''
    let options = {}
    try {
      const payload = event.data ? event.data.json() : null
      const note = payload && payload.notification
      if (note) {
        title = String(note.title || '')
        options = {
          body: note.body ? String(note.body) : undefined,
          data: { url: note.navigate ? String(note.navigate) : '/' },
          lang: note.lang || 'bg',
        }
      }
    } catch {
      // An unreadable payload still gets a notification below.
    }
    event.waitUntil(
      self.registration.showNotification(title, {
        icon: '/icon-192.png',
        badge: '/icon-192.png',
        ...options,
      }),
    )
  })

  self.addEventListener('notificationclick', (event) => {
    event.notification.close()
    const data = event.notification.data
    const target = new URL((data && data.url) || '/', self.location.origin).href
    event.waitUntil(
      self.clients
        .matchAll({ type: 'window', includeUncontrolled: true })
        .then((windows) => {
          const open = windows.find((client) => 'focus' in client)
          if (open) {
            return open.focus().then((client) =>
              'navigate' in client ? client.navigate(target) : client,
            )
          }
          return self.clients.openWindow(target)
        }),
    )
  })

  self.addEventListener('fetch', (event) => {
    const request = event.request
    if (request.method !== 'GET') return
    const url = new URL(request.url)
    // Clerk, Convex and server functions always go to the network.
    if (url.origin !== self.location.origin) return
    if (url.pathname.startsWith('/_serverFn')) return

    if (request.mode === 'navigate') {
      event.respondWith(
        caches
          .match(SHELL, { cacheName: SHELL_CACHE })
          .then((cached) => cached || fetch(request)),
      )
      return
    }

    if (url.pathname.startsWith('/assets/')) {
      event.respondWith(
        caches.open(ASSET_CACHE).then(async (cache) => {
          const cached = await cache.match(request, { ignoreVary: true })
          if (cached) return cached
          const response = await fetch(request)
          const type = response.headers.get('content-type') || ''
          // A missing file can come back as the HTML shell: never keep that.
          if (response.ok && !type.startsWith('text/html')) {
            event.waitUntil(cache.put(request, response.clone()))
          }
          return response
        }),
      )
      return
    }

    if (SHELL_FILES.includes(url.pathname)) {
      event.respondWith(
        caches
          .match(request, { cacheName: SHELL_CACHE, ignoreSearch: true, ignoreVary: true })
          .then((cached) => cached || fetch(request)),
      )
    }
  })
}
`
}
